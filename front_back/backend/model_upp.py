import random
import re


class MockModelRunner:
    """Лёгкая заглушка с тем же интерфейсом, что и настоящий ML runner."""

    def generate_response(self, full_prompt: str) -> str:
        matches = re.findall(
            r"(?:Ситуация|Пользователь):\s*(.*?)(?=\nРассуждение:|$)",
            full_prompt,
            flags=re.DOTALL,
        )
        message = matches[-1].strip() if matches else full_prompt.strip()
        lowered = message.lower()

        if any(word in lowered for word in ("тревог", "тревож", "страш", "боюсь", "паник")):
            responses = (
                "Похоже, сейчас внутри много тревоги, и с ней непросто оставаться наедине. "
                "Давай немного замедлимся: какая мысль пугает тебя сильнее всего?",
                "Я слышу, насколько напряжённо тебе сейчас. Иногда тревога будто заранее проживает "
                "самый плохой сценарий — что именно она рисует тебе сейчас?",
            )
        elif any(word in lowered for word in ("груст", "одинок", "плохо", "тяжело")):
            responses = (
                "Мне жаль, что тебе приходится нести это сейчас. Здесь не нужно подбирать правильные "
                "слова — можешь рассказать, что в этом переживании болит больше всего?",
                "Похоже, тебе действительно тяжело. Я рядом и готов выслушать без оценок — "
                "с какого момента это чувство стало особенно сильным?",
            )
        elif any(word in lowered for word in ("привет", "здравств", "hello")):
            responses = (
                "Привет. Я рядом и готов тебя выслушать. Как ты себя чувствуешь прямо сейчас?",
                "Привет. Здесь можно говорить честно и в своём темпе. Что привело тебя сегодня?",
            )
        elif any(word in lowered for word in ("спасибо", "благодар")):
            responses = (
                "Пожалуйста. Мне важно, что этот разговор оказался для тебя полезным. "
                "Хочешь ещё немного побыть с этой темой или сейчас лучше сделать паузу?",
            )
        else:
            responses = (
                "Спасибо, что поделился этим. Мне хочется лучше понять тебя: "
                "что во всей этой ситуации сейчас отзывается сильнее всего?",
                "Я тебя слышу. Похоже, за этим есть что-то действительно важное для тебя. "
                "Какие чувства появляются, когда ты об этом говоришь?",
                "Давай побудем с этим чуть внимательнее. Что тебе больше всего хотелось бы "
                "получить или почувствовать в этой ситуации?",
            )

        return random.choice(responses)


_model_runner: MockModelRunner | None = None


def load_model() -> None:
    global _model_runner

    if _model_runner is None:
        _model_runner = MockModelRunner()


def get_model() -> MockModelRunner:
    if _model_runner is None:
        raise RuntimeError("Model is not loaded")

    return _model_runner
