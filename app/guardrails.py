# Список триггерных основ слов для детекции селфхарма/суицида
DANGER_KEYWORDS = [
    "суицид", "убить себя", "покончить с", "вскрыть вены", 
    "наглотаться таблеток", "спрыгнуть", "не хочу жить", "смерть"
]

